// Generates docs/DATA_SOURCES.md from server/core/catalogue.js so the doc never drifts from the code.
import { CATALOGUE } from "../server/core/catalogue.js";
import { writeFileSync } from "node:fs";
const row = (p) => `| ${p.name} | ${p.org} | ${p.category} | ${p.auth} | ${p.rate} | ${p.license} | ${p.modules.join(", ") || "-"} | [docs](${p.docs}) |`;
const head = "| Provider | Organization | Category | Authentication | Rate limits | Licence | Modules | Docs |\n|---|---|---|---|---|---|---|---|\n";
const out = `# Data sources

Generated by \`node scripts/gen-sources-doc.mjs\` from \`server/core/catalogue.js\`. Verify licensing, rate limits and attribution on each provider's site before production use. Nothing here is assumed to be free or unrestricted.

## Integrated (adapter exists)
${head}${CATALOGUE.filter((p) => p.integration === "integrated").map(row).join("\n")}

## Catalogued (known, not integrated yet)
${head}${CATALOGUE.filter((p) => p.integration === "catalogued").map(row).join("\n")}

## Not scraped
Worldometers publishes no API and restricts copying; it mostly republishes UN and World Bank figures that ORBIS takes from the original sources.

## Verification status
Adapters are tested against fixtures written from each provider's documented response format. Live connectivity could not be tested in the build sandbox; check the **API Management Center** on your machine.
`;
writeFileSync(new URL("../docs/DATA_SOURCES.md", import.meta.url), out); console.log("ok");
